const set = JSON.parse(readFileSync(new URL('../node_modules/@iconify-json/ph/icons.json', import.meta.url), 'utf8'));
const lines = Object.entries(MAP).map(([name, from]) => {
  const body = set.icons[from]?.body;
  if (!body) throw new Error(`no icon "${from}" in Phosphor`);
  return `  ${name}: '${body.replaceAll("'", "\\'")}',`;
});
writeFileSync(
  new URL('../src/ui/iconSet.ts', import.meta.url),
  `// Generated by scripts/build-icons.mjs from Phosphor, regular weight (phosphoricons.com, MIT). Do not edit by hand.\nexport const ICON_BODIES = {\n${lines.join('\n')}\n} as const;\n`,
);
